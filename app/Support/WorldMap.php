    /** Where a longitude falls in the drawing. */
    public static function x(float $lon): float
    {
        return max(-180.0, min(180.0, $lon)) + 180.0;
    }

    /** Where a latitude falls. Anything off the cropped edges is pinned to it. */
    public static function y(float $lat): float
    {
        return self::TOP_LAT - max(self::BOTTOM_LAT, min(self::TOP_LAT, $lat));
    }

    /** The coastlines as one path, to be filled even-odd. */
    public static function landPath(): string
    {
        $parts = [];

        foreach (self::LAND as $ring) {
            $segment = '';
            for ($i = 0, $n = count($ring); $i < $n; $i += 2) {
                $segment .= ($i === 0 ? 'M' : 'L')
                    . self::round(self::x($ring[$i])) . ' '
                    . self::round(self::y($ring[$i + 1]));
            }
            $parts[] = $segment . 'Z';
        }

        return implode('', $parts);
    }

    /**
     * Meridians and parallels every 30°, as one path. They are what tells the
     * eye this is a projection of a globe rather than a decorative blob.
     */
    public static function graticulePath(): string
    {
        $d = '';

        for ($lon = -150.0; $lon <= 150.0; $lon += 30.0) {
            $d .= 'M' . self::round(self::x($lon)) . ' 0V' . self::round(self::HEIGHT);
        }

        for ($lat = -30.0; $lat <= 60.0; $lat += 30.0) {
            $d .= 'M0 ' . self::round(self::y($lat)) . 'H' . self::round(self::WIDTH);
        }

        return $d;
    }

    private static function round(float $value): string
    {
        return rtrim(rtrim(number_format($value, 1, '.', ''), '0'), '.');
    }
